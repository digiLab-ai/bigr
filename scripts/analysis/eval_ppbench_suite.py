"""eval_ppbench_suite — per-type selection-rule suite + guide diagnostics for PPBench.

Complements eval_ppbench.py (per-type guided-MAP vs TRM baseline). From the unguided
(beta=0) particle traces it computes, per puzzle type and aggregate:

  * selection-rule suite: base (single rollout), plurality (majority vote), terminal-Q,
    path-sum, oracle — run_trace_analyses.py's exact definitions;
  * guide diagnostics: Q-spread (std of the terminal Q across particles) and
    Delta_n (mean Q of correct particles minus incorrect — the discrimination gap).

Examples aligned to the type table by input-content hash (as in eval_ppbench.py).
Plurality uses first-index tie-breaking, as in run_trace_analyses.py.

The cached outputs are assets/runs/analysis/ablations/ppbench/suite/ppbench_suite_by_type_{val,golden}.json
(Table 9 by type), regenerated by ``bash scripts/run_experiments.sh --ppbench``.

Usage:
  python scripts/analysis/eval_ppbench_suite.py \
      --run-glob 'assets/runs/analysis/ablations/ppbench/golden/pf_ppbench_unguided_seed*' \
      --data-dir data/ppbench --split test \
      --out assets/runs/analysis/ablations/ppbench/suite/ppbench_suite_by_type_golden.json
"""
from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
from pathlib import Path

import numpy as np

RULES = ["base", "plurality", "terminal_q", "path_sum", "oracle"]
DIAG = ["q_spread", "delta_n"]  # per-type guide diagnostics


def _hash(arr: np.ndarray) -> str:
    return hashlib.md5(np.ascontiguousarray(np.asarray(arr, dtype=np.int64)).tobytes()).hexdigest()


def _sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def _select_hits(scores, correct_T):  # per-example 0/1: is the argmax-score particle correct
    return correct_T[np.arange(len(scores)), scores.argmax(1)].astype(float)


def _plurality_hits(preds_T, correct_T):  # per-example: is the modal-decoded particle correct
    picks = []
    for b in range(len(preds_T)):
        groups: dict[bytes, tuple[int, int]] = {}
        for s in range(preds_T.shape[1]):
            key = preds_T[b, s].tobytes()
            cnt, first = groups.get(key, (0, s))
            groups[key] = (cnt + 1, first)
        picks.append(max(groups.values(), key=lambda t: t[0])[1])
    return correct_T[np.arange(len(preds_T)), picks].astype(float)


def eval_run_dir(run_dir: Path, type_lut: dict, type_names: list[str]) -> dict:
    q = np.load(run_dir / "particle_qlogits.npy")          # (N, T, S)
    correct = np.load(run_dir / "particle_correct.npy")    # (N, T, S)
    preds = np.load(run_dir / "particle_preds.npy", mmap_mode="r")  # (N, T, S, L)
    inputs = np.load(run_dir / "inputs.npy")               # (N, L)
    N = q.shape[0]
    q_T, correct_T = q[:, -1, :], correct[:, -1, :]
    pathsum = np.log(_sigmoid(q)).sum(axis=1)              # (N, S)
    preds_T = np.asarray(preds[:, -1])                     # (N, S, L)
    qspread = q_T.std(axis=1)                              # (N,) spread of terminal Q across particles

    hits = {
        "base": correct_T.mean(axis=1),
        "plurality": _plurality_hits(preds_T, correct_T),
        "terminal_q": _select_hits(q_T, correct_T),
        "path_sum": _select_hits(pathsum, correct_T),
        "oracle": correct_T.any(axis=1).astype(float),
    }
    tidx = np.array([type_lut.get(_hash(inputs[i]), -1) for i in range(N)])

    def group(mask):
        m = mask & (tidx >= 0)
        if not m.any():
            return None
        qc, cc = q_T[m].ravel(), correct_T[m].ravel()      # Q + correctness over (puzzle, particle)
        pos, neg = qc[cc == 1], qc[cc == 0]
        delta_n = float(pos.mean() - neg.mean()) if len(pos) and len(neg) else float("nan")
        return {"n": int(m.sum()),
                **{r: float(hits[r][m].mean()) for r in RULES},
                "q_spread": float(qspread[m].mean()),
                "delta_n": delta_n}

    per_type = {t: group(tidx == i) for i, t in enumerate(type_names)}
    return {"per_type": {t: v for t, v in per_type.items() if v}, "aggregate": group(np.ones(N, bool))}


def _mean_std(per, getter) -> dict:
    keys = RULES + DIAG
    vals = {r: [] for r in keys}
    for p in per:
        g = getter(p)
        if g:
            for r in keys:
                if r in g:
                    vals[r].append(g[r])
    return {r: [float(np.nanmean(v)), float(np.nanstd(v))] for r, v in vals.items() if v}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-glob", required=True, help="glob for unguided seed run dirs")
    ap.add_argument("--data-dir", type=Path, default=Path("data/ppbench"))
    ap.add_argument("--split", default="test")
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()

    meta = json.loads((args.data_dir / "metadata.json").read_text())
    type_names = meta["types"]
    d = args.data_dir / args.split
    inputs = np.load(d / "all__inputs.npy")
    types = np.load(d / "all__types.npy")
    type_lut = {_hash(inputs[i]): int(types[i]) for i in range(len(inputs))}

    dirs = sorted(
        Path(x) for x in glob.glob(args.run_glob, recursive=True)
        if os.path.isdir(x) and (Path(x) / "particle_qlogits.npy").exists()
    )
    if not dirs:
        ap.error(f"no unguided trace dirs (with particle_qlogits.npy) match {args.run_glob}")
    per = [eval_run_dir(dd, type_lut, type_names) for dd in dirs]

    summary = {"split": args.split, "num_seeds": len(dirs), "rules": RULES, "diagnostics": DIAG,
               "aggregate": _mean_std(per, lambda p: p["aggregate"]),
               "types": {t: _mean_std(per, lambda p, t=t: p["per_type"].get(t)) for t in type_names}}

    print(f"\nPPBench selection-rule suite by type ({args.split}, unguided cloud, {len(dirs)} seeds) — exact %:")
    print(f"{'type':<10}" + "".join(f"{r:>16}" for r in RULES))

    def fmt(dd):
        return "".join(f"{dd[r][0] * 100:9.1f}±{dd[r][1] * 100:<4.1f}" if r in dd else f"{'—':>16}" for r in RULES)

    for t in type_names:
        if summary["types"][t]:
            print(f"{t:<10}{fmt(summary['types'][t])}")
    print(f"{'AGG':<10}{fmt(summary['aggregate'])}")

    print(f"\nPer-type guide diagnostics ({args.split}) — Q-spread (std of terminal Q across "
          f"particles) and Delta_n (mean Q of correct - incorrect particles):")
    print(f"{'type':<10}{'q_spread':>16}{'delta_n':>16}")

    def fmtd(dd):
        return "".join(f"{dd[r][0]:10.3f}±{dd[r][1]:<5.3f}" if r in dd else f"{'—':>16}" for r in DIAG)

    for t in type_names:
        if summary["types"][t]:
            print(f"{t:<10}{fmtd(summary['types'][t])}")
    print(f"{'AGG':<10}{fmtd(summary['aggregate'])}")

    out = args.out or (dirs[0].parent / "ppbench_suite_by_type.json")
    Path(out).write_text(json.dumps(summary, indent=2))
    print(f"\nSaved {out}")


if __name__ == "__main__":
    main()
