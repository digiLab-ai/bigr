"""run_depth_baseline — deterministic TRM depth profile, no particle filter (Table 11).

Runs the checkpoint-faithful deterministic recursion to --total-steps and saves the
per-cycle exact-solve profile (trm_depth_profile.csv); only the deterministic baseline of
run_pf.py is computed, not the filter.

With --per-type (the default for --profile ppbench) it also writes the per-example
breakdown the register reads for the PPBench rows of Table 11: aggregate.csv (depth, exact:
the per-example exact-solve rate after every cycle), per_type.csv (depth, one column per
puzzle type) and per_puzzle.csv (puzzle, type, exact@48 ... exact@768). Puzzle types come
from ``<data_dir>/<split>/all__types.npy`` (same row order as the loader, which does not
shuffle and keeps the final partial batch) and ``<data_dir>/metadata.json``.

Cached runs: assets/runs/analysis/ablations/baselines/e2_depth_sudoku (256 puzzles, N=768),
regenerated by ``bash scripts/run_experiments.sh --profile sudoku_extreme --depth-baseline``,
and assets/runs/analysis/ppbench_depth/ppbench_depth_{val,test} (253 and 42 puzzles, N=768),
regenerated by ``bash scripts/run_experiments.sh --ppbench-depth``.

Usage
-----
    python scripts/analysis/run_depth_baseline.py \
        --profile sudoku_extreme --split test --total-steps 768 --batch-size 16 --n-batches 16 \
        --out assets/runs/analysis/ablations/baselines/e2_depth_sudoku

    python scripts/analysis/run_depth_baseline.py \
        --profile ppbench --split val --total-steps 768 --batch-size 14 --n-batches 9999 \
        --out assets/runs/analysis/ppbench_depth/ppbench_depth_val
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parents[1]
for p in (REPO_ROOT / "src", REPO_ROOT / "scripts" / "exps"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from bigr import load_trm_backbone_checkpoint, select_device  # noqa: E402
from run_pf import PROFILE_DEFAULTS, load_batches, run_trm_baseline  # noqa: E402

DEPTH_MARKS = (48, 96, 192, 384, 768)


def write_per_type_tables(flags: np.ndarray, data_dir: Path, split: str, out: Path) -> pd.Series:
    """Write aggregate.csv, per_type.csv and per_puzzle.csv from per-example exact-solve flags.

    ``flags`` is the (N_examples, n_cycles) bool array of ``run_trm_baseline`` in loader row
    order, which is the row order of ``<data_dir>/<split>/all__types.npy``. Rates are float32
    means, as in the cached artefacts. Returns the aggregate profile indexed by depth.
    """
    meta = json.loads((data_dir / "metadata.json").read_text())
    type_idx = np.load(data_dir / split / "all__types.npy")
    if len(type_idx) != flags.shape[0]:
        raise ValueError(
            f"{len(type_idx)} puzzle types in {split}/all__types.npy but {flags.shape[0]} examples were run; "
            "--n-batches must cover the whole split"
        )
    index_to_name = {int(i): name for name, i in meta["type_index"].items()}
    names = np.array([index_to_name[int(i)] for i in type_idx])
    depth = np.arange(1, flags.shape[1] + 1)

    aggregate = pd.DataFrame({"depth": depth, "exact": flags.mean(axis=0, dtype=np.float32)})
    aggregate.to_csv(out / "aggregate.csv", index=False)

    per_type = {"depth": depth}
    for name in meta["types"]:
        rows = flags[names == name]
        per_type[name] = (
            rows.mean(axis=0, dtype=np.float32)
            if len(rows)
            else np.full(flags.shape[1], np.nan, dtype=np.float32)
        )
    pd.DataFrame(per_type).to_csv(out / "per_type.csv", index=False)

    per_puzzle = {"puzzle": np.arange(flags.shape[0]), "type": names}
    for n in DEPTH_MARKS:
        if n <= flags.shape[1]:
            per_puzzle[f"exact@{n}"] = flags[:, n - 1].astype(int)
    pd.DataFrame(per_puzzle).to_csv(out / "per_puzzle.csv", index=False)
    return aggregate.set_index("depth")["exact"]


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Deterministic TRM depth profile to --total-steps (Table 11); no particle filter.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    ap.add_argument("--profile", default="sudoku_extreme", choices=sorted(PROFILE_DEFAULTS))
    ap.add_argument("--split", default="test", choices=["test", "impossible", "val"])
    ap.add_argument("--total-steps", type=int, default=768)
    ap.add_argument("--batch-size", type=int, default=16)
    ap.add_argument("--n-batches", type=int, default=16)
    ap.add_argument(
        "--per-type",
        action=argparse.BooleanOptionalAction,
        default=None,
        help="Also write aggregate.csv, per_type.csv and per_puzzle.csv from <data_dir>/<split>/all__types.npy "
        "(default: on for --profile ppbench).",
    )
    ap.add_argument("--device", default=None)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    if args.per_type is None:
        args.per_type = args.profile == "ppbench"

    cfg = PROFILE_DEFAULTS[args.profile]
    device = torch.device(args.device) if args.device else select_device()
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "config.json").write_text(
        json.dumps({k: str(v) if isinstance(v, Path) else v for k, v in vars(args).items()}, indent=2)
    )

    trm = load_trm_backbone_checkpoint(cfg["checkpoint"], map_location=device, use_ema=True)
    trm.eval().to(device)
    batches = load_batches(
        data_dir=cfg["data_dir"],
        split=args.split,
        batch_size=args.batch_size,
        n_batches=args.n_batches,
        device=device,
    )
    with torch.no_grad():
        df, _, flags = run_trm_baseline(
            trm, batches, device=device, total_steps=args.total_steps, return_per_example=True
        )
    df.to_csv(args.out / "trm_depth_profile.csv", index=False)
    if args.per_type:
        tail = write_per_type_tables(flags, Path(cfg["data_dir"]), args.split, args.out)
    else:
        tail = df.groupby("step")["exact_solved"].mean()
    marks = [n for n in DEPTH_MARKS if n in tail.index]
    print({int(n): round(float(tail.loc[n]), 4) for n in marks})


if __name__ == "__main__":
    main()
