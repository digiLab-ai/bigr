"""eval_ppbench — per-type exact-match accuracy for a PPBench run_pf output.

PPBench puzzles are single-solution, so the paper's per-puzzle metric is exact whole-grid
match. This post-hoc evaluator reports, per puzzle type (sudoku / lightup / nurikabe / tapa)
and aggregate:

  * guided MAP exact accuracy   (the particle filter's argmax answer)
  * TRM baseline exact accuracy (deterministic rollout, from trm_preds.npy)

It reads a ``run_pf.py --save-particle-trace`` output dir (single run or k-fold
``fold_01/`` ..). Predictions are aligned to the dataset **by input content** (saved
``inputs.npy``), then each example's true label + puzzle type are looked up from the
dataset split (``all__labels.npy`` / ``all__types.npy``). Fold or seed results aggregate as
mean ± std. PPBench answers are unique, so exact match is the only metric.

The cached outputs are assets/runs/analysis/ablations/ppbench/{val,golden}/ppbench_metrics_*.json
(Table 1 PPBench column, Tables 9-10), regenerated by ``bash scripts/run_experiments.sh --ppbench``.

Usage:
  python scripts/exps/eval_ppbench.py \
      --run-dir assets/runs/analysis/ablations/ppbench/golden/pf_ppbench_seed31 \
      --data-dir data/ppbench --split test
  python scripts/exps/eval_ppbench.py \
      --run-glob 'assets/runs/analysis/ablations/ppbench/golden/pf_ppbench_seed*' --split test \
      --out assets/runs/analysis/ablations/ppbench/golden/ppbench_metrics_guided_seeds.json
"""

from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
from collections import defaultdict
from pathlib import Path

import numpy as np

IGNORE_LABEL_ID = -100


def _hash(arr: np.ndarray) -> str:
    # Canonical dtype: run inputs.npy are int64 (dataloader .long()), dataset int32.
    return hashlib.md5(np.ascontiguousarray(np.asarray(arr, dtype=np.int64)).tobytes()).hexdigest()


def _final_step_preds(arr: np.ndarray) -> np.ndarray:
    """Last populated step slice of a (N, T, ...) trace (skip all-(-1) padding steps)."""
    if arr.ndim == 2:  # already (N, L)
        return arr
    for t in range(arr.shape[1] - 1, -1, -1):
        sl = arr[:, t]
        if not np.all(sl == -1):
            return sl
    return arr[:, -1]


def build_lookup(data_dir: Path, split: str):
    """input-hash -> (label row, type index) from the dataset split."""
    d = data_dir / split
    inputs = np.load(d / "all__inputs.npy")
    labels = np.load(d / "all__labels.npy")
    types = np.load(d / "all__types.npy")
    lut = {}
    for i in range(len(inputs)):
        lut[_hash(inputs[i])] = (labels[i], int(types[i]))
    return lut


def _exact(pred: np.ndarray, label: np.ndarray) -> bool:
    mask = label != IGNORE_LABEL_ID
    return bool(np.array_equal(pred[mask], label[mask]))


def eval_run_dir(run_dir: Path, lut: dict, type_names: list[str]) -> dict:
    """Per-type + aggregate exact accuracy for one run/fold."""
    map_preds = _final_step_preds(np.load(run_dir / "map_preds.npy"))  # (N, L)
    inputs = np.load(run_dir / "inputs.npy")
    trm_path = run_dir / "trm_preds.npy"
    trm_preds = np.load(trm_path) if trm_path.exists() else None
    if trm_preds is not None and trm_preds.shape[0] != map_preds.shape[0]:
        trm_preds = None

    hit = defaultdict(int)
    tot = defaultdict(int)
    trm_hit = defaultdict(int)
    for i in range(len(map_preds)):
        h = _hash(inputs[i])
        if h not in lut:
            continue
        label, ti = lut[h]
        tname = type_names[ti]
        tot[tname] += 1
        if _exact(map_preds[i], label):
            hit[tname] += 1
        if trm_preds is not None and _exact(trm_preds[i], label):
            trm_hit[tname] += 1

    res = {"num_examples": int(sum(tot.values()))}
    per_type = {}
    for t in type_names:
        if tot[t]:
            per_type[t] = {
                "n": tot[t],
                "guided_exact": hit[t] / tot[t],
                **({"trm_exact": trm_hit[t] / tot[t]} if trm_preds is not None else {}),
            }
    res["per_type"] = per_type
    n = sum(tot.values())
    if n:
        res["guided_exact_agg"] = sum(hit.values()) / n
        if trm_preds is not None:
            res["trm_exact_agg"] = sum(trm_hit.values()) / n
    return res


def _aggregate(per_unit: list, type_names: list, unit: str) -> dict:
    """Aggregate per-run results (folds OR seeds) into mean +/- std.

    Applies to both the guided MAP (stochastic -> real seed variance) and the TRM baseline
    (deterministic -> std ~ 0; reported anyway for a consistent per-type table).
    """
    summary = {f"num_{unit}s": len(per_unit), f"{unit}s": per_unit}
    agg_keys = sorted({k for u in per_unit for k in u if k.endswith("_agg")})
    for k in agg_keys:
        vals = [u[k] for u in per_unit if k in u]
        if vals:
            summary[f"{k}_mean"] = float(np.mean(vals))
            summary[f"{k}_std"] = float(np.std(vals))
    for t in type_names:
        for metric in ("guided_exact", "trm_exact"):
            vals = [
                u["per_type"][t][metric]
                for u in per_unit
                if t in u.get("per_type", {}) and metric in u["per_type"][t]
            ]
            if vals:
                summary[f"{t}_{metric}_mean"] = float(np.mean(vals))
                summary[f"{t}_{metric}_std"] = float(np.std(vals))
    return summary


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-dir", type=Path, default=None, help="single run or fold parent.")
    ap.add_argument(
        "--run-glob",
        type=str,
        default=None,
        help="glob matching multiple seed run dirs to aggregate as mean+/-std over seeds "
        "(e.g. 'assets/runs/analysis/ablations/ppbench/golden/pf_ppbench_seed*'). Golden is small, so seeds give "
        "confidence where folds can't.",
    )
    ap.add_argument("--data-dir", type=Path, default=Path("data/ppbench"))
    ap.add_argument("--split", default="test")
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()
    if not args.run_dir and not args.run_glob:
        ap.error("provide --run-dir or --run-glob")

    meta = json.loads((args.data_dir / "metadata.json").read_text())
    type_names = meta["types"]
    lut = build_lookup(args.data_dir, args.split)

    if args.run_glob:  # aggregate across SEEDS (each matched dir = one stochastic run)
        dirs = sorted(
            Path(d) for d in glob.glob(args.run_glob, recursive=True)
            if os.path.isdir(d) and (Path(d) / "map_preds.npy").exists()
        )
        if not dirs:
            ap.error(f"no seed run dirs (with map_preds.npy) match {args.run_glob}")
        per = [{"run": d.name, **eval_run_dir(d, lut, type_names)} for d in dirs]
        summary = {"split": args.split, **_aggregate(per, type_names, "seed")}
        out = args.out or (dirs[0].parent / "ppbench_metrics_seeds.json")
    else:
        fold_dirs = sorted(d for d in args.run_dir.glob("fold_*") if (d / "map_preds.npy").exists())
        if fold_dirs:
            per = [{"fold": fd.name, **eval_run_dir(fd, lut, type_names)} for fd in fold_dirs]
            summary = {"split": args.split, **_aggregate(per, type_names, "fold")}
        else:
            summary = {"split": args.split, "num_folds": 1, **eval_run_dir(args.run_dir, lut, type_names)}
        out = args.out or (args.run_dir / "ppbench_metrics.json")

    out.write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary, indent=2))
    print(f"\nSaved {out}")


if __name__ == "__main__":
    main()
