"""run_test_time_compute - Compute-vs-accuracy frontier for test-time inference (Table 13).

The benchmark evaluates guided and unguided particle inference at several
particle budgets and reports accuracy as a function of normalised F_theta calls:

    F_theta calls = particles * outer_step

The cached run is assets/runs/analysis/ablations/baselines/e1c_frontier_sudoku
(S in {1, 2, 4, 8, 16}, 16 x 32 puzzles, 3 folds), regenerated by
``bash scripts/run_experiments.sh --profile sudoku_extreme --frontier``.

Outputs
-------
    <out>/config.json
    <out>/fold_manifest.json                 (k-fold only)
    <out>/run_manifest.csv
    <out>/trm_depth_profile.csv
    <out>/trm_depth_profile_summary.csv      (k-fold only)
    <out>/compute_frontier.csv
    <out>/compute_summary.csv
    <out>/quality_table.csv, quality_table.md
    <out>/{guided,unguided}/S_<particles>/...

Examples
--------
# The Table 13 protocol
python scripts/exps/run_test_time_compute.py --profile sudoku_extreme --split test \\
    --particles 1 2 4 8 16 --total-steps 48 --sigma 0.3 --beta 0.25 --ess-threshold 0.3 \\
    --batch-size 16 --n-batches 32 --num-folds 3 --seed 31 \\
    --out assets/runs/analysis/ablations/baselines/e1c_frontier_sudoku

# Quick smoke check
python scripts/exps/run_test_time_compute.py --smoke --out tmp/ttc_smoke
"""

