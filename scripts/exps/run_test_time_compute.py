DEFAULT_PARTICLES = [1, 2, 4, 8, 16]
MODE_SPECS = [("guided", None), ("unguided", 0.0)]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run the test-time compute frontier benchmark.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--profile",
        default="sudoku_extreme",
        choices=sorted(PROFILE_DEFAULTS),
        help="Dataset/checkpoint profile preset.",
    )
    parser.add_argument("--checkpoint", type=Path, default=None)
    parser.add_argument("--data-dir", type=Path, default=None)
    parser.add_argument("--split", default="test", choices=["test", "impossible"])
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help=(
            "Output directory (default: assets/runs/analysis/ablations/baselines/"
            "e1c_frontier_<sudoku|maze>[_<split>])."
        ),
    )
    parser.add_argument(
        "--device",
        default=None,
        help="Target device. Auto-selects CUDA > MPS > CPU if omitted.",
    )
    parser.add_argument("--particles", nargs="+", type=int, default=DEFAULT_PARTICLES)
    parser.add_argument("--total-steps", type=int, default=48)
    parser.add_argument("--sigma", type=float, default=0.3)
    parser.add_argument("--beta", type=float, default=0.25)
    parser.add_argument("--ess-threshold", type=float, default=0.3)
    parser.add_argument("--seed", type=int, default=31)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--n-batches", type=int, default=16)
    parser.add_argument("--num-folds", type=int, default=1)
    parser.add_argument("--fold-seed", type=int, default=None)
    parser.add_argument(
        "--smoke",
        action="store_true",
        help="Quick local check: S in {1,4}, 2 batches, 12 steps.",
    )
    parser.add_argument(
        "--disable-step-cpu-metrics",
        action="store_true",
        help="Skip per-step diagnostic materialisation/aggregation.",
    )
    return parser.parse_args()


def _write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")


def _particle_tag(particles: int) -> str:
    return f"S_{particles:02d}"


def _default_out(args: argparse.Namespace) -> Path:
    bench = "maze" if args.profile == "maze_hard" else "sudoku"
    split_suffix = "" if args.split == "test" else f"_{args.split}"
    return (
        REPO_ROOT / "assets" / "runs" / "analysis" / "ablations" / "baselines"
        / f"e1c_frontier_{bench}{split_suffix}"
    )


def _pf_args(
    args: argparse.Namespace,
    *,
    particles: int,
    beta: float,
    out_dir: Path,
) -> SimpleNamespace:
    return SimpleNamespace(
        profile=args.profile,
        checkpoint=args.checkpoint,
        data_dir=args.data_dir,
        split=args.split,
        out=out_dir,
        device=args.device,
        particles=particles,
        total_steps=args.total_steps,
        sigma=args.sigma,
        beta=beta,
        ess_threshold=args.ess_threshold,
        seed=args.seed,
        batch_size=args.batch_size,
        n_batches=args.n_batches,
        smoke=False,
        save_particle_scores=None,
        checkpoint_all_steps=False,
        num_folds=args.num_folds,
        fold_seed=args.fold_seed,
        disable_step_cpu_metrics=args.disable_step_cpu_metrics,
    )


def _copy_baseline(
    *,
    baseline_source: Path | None,
    out_dir: Path,
    num_folds: int,
) -> None:
    if baseline_source is None:
        return
    if num_folds == 1:
        source = baseline_source / "trm_depth_profile.csv"
        if source.exists():
            out_dir.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, out_dir / "trm_depth_profile.csv")
        return

    for fold_idx in range(1, num_folds + 1):
        fold_name = f"fold_{fold_idx:02d}"
        source = baseline_source / fold_name / "trm_depth_profile.csv"
        if source.exists():
            fold_out = out_dir / fold_name
            fold_out.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, fold_out / "trm_depth_profile.csv")


def _run_condition(
    *,
    args: argparse.Namespace,
    mode: str,
    particles: int,
    beta: float,
    trm,
    device: torch.device,
    raw_batches: list[dict],
    fold_batches: list[list[dict]] | None,
    fold_infos: list[FoldBatchInfo] | None,
    out_dir: Path,
    baseline_source: Path | None,
) -> None:
    embedder = TRMCoreEmbedder(trm)
    decoder = TRMCoreDecoder(trm)
    q_head = TRMCoreQHead(trm)
    f_theta = TRMNativeCycleFTheta(trm)
    pf_args = _pf_args(args, particles=particles, beta=beta, out_dir=out_dir)
    _copy_baseline(
        baseline_source=baseline_source,
        out_dir=out_dir,
        num_folds=args.num_folds,
    )

    if args.num_folds == 1:
        _run_pf_single(
            args=pf_args,
            trm=trm,
            device=device,
            embedder=embedder,
            decoder=decoder,
            q_head=q_head,
            f_theta=f_theta,
            raw_batches=raw_batches,
            out_dir=out_dir,
            save_particle_scores_dir=None,
            save_particle_trace_dir=None,
        )
        return

    assert fold_batches is not None
    assert fold_infos is not None
    fold_outputs = []
    for fold_idx, (fold_raw_batches, fold_info) in enumerate(
        zip(fold_batches, fold_infos),
        start=1,
    ):
        fold_name = f"fold_{fold_idx:02d}"
        fold_out = out_dir / fold_name
        print(
            f"[{mode}/{_particle_tag(particles)}/{fold_name}] "
            f"examples={fold_info.num_examples} batches={fold_info.num_batches}"
        )
        fold_outputs.append(
            _run_pf_single(
                args=pf_args,
                trm=trm,
                device=device,
                embedder=embedder,
                decoder=decoder,
                q_head=q_head,
                f_theta=f_theta,
                raw_batches=fold_raw_batches,
                out_dir=fold_out,
                save_particle_scores_dir=None,
                save_particle_trace_dir=None,
                fold_meta={
                    "fold_mode": True,
                    "fold_index": fold_idx,
                    "fold_name": fold_name,
                    "num_folds": args.num_folds,
                    "fold_seed": args.fold_seed,
                    "fold_num_examples": fold_info.num_examples,
                    "fold_num_batches": fold_info.num_batches,
                    "mode": mode,
                    "particles": particles,
                    "split": args.split,
                },
            )
        )

    _summarize_fold_outputs(fold_outputs, out_dir, fold_infos, pf_args)


def _normalise_trm_frame(frame: pd.DataFrame) -> pd.DataFrame:
    return frame[["step", "exact_solved"]].sort_values("step").reset_index(drop=True)


def _load_trm_profile(run_dir: Path, *, num_folds: int) -> pd.DataFrame:
    if num_folds == 1:
        frame = _normalise_trm_frame(pd.read_csv(run_dir / "trm_depth_profile.csv"))
        frame["exact_solved_std"] = 0.0
        return frame

    rows = []
    for fold_idx in range(1, num_folds + 1):
        fold_dir = run_dir / f"fold_{fold_idx:02d}"
        frame = _normalise_trm_frame(pd.read_csv(fold_dir / "trm_depth_profile.csv"))
        rows.append(frame.assign(fold=fold_idx))
    merged = pd.concat(rows, ignore_index=True)
    summary = (
        merged.groupby("step", as_index=False)["exact_solved"]
        .agg(["mean", "std"])
        .reset_index()
        .rename(columns={"mean": "exact_solved", "std": "exact_solved_std"})
    )
    summary["exact_solved_std"] = summary["exact_solved_std"].fillna(0.0)
    return summary.sort_values("step").reset_index(drop=True)


def _load_step_profile(run_dir: Path, *, num_folds: int) -> pd.DataFrame:
    if num_folds == 1:
        frame = pd.read_csv(run_dir / "step_metrics.csv")
        for column in ["exact_accuracy", "any_exact_rate", "mean_ess"]:
            frame[f"{column}_std"] = 0.0
        return frame

    summary = pd.read_csv(run_dir / "step_metrics_summary.csv")
    out = pd.DataFrame({"step": summary["step"]})
    for column in ["exact_accuracy", "any_exact_rate", "mean_ess"]:
        out[column] = summary[f"{column}_mean"]
        out[f"{column}_std"] = summary[f"{column}_std"].fillna(0.0)
    return out


def _add_ci_columns(
    frame: pd.DataFrame,
    columns: list[str],
    *,
    num_folds: int,
) -> pd.DataFrame:
    out = frame.copy()
    for column in columns:
        std_col = f"{column}_std"
        if column not in out.columns or std_col not in out.columns:
            continue
        ci = ci_half_width(out[std_col].to_numpy(dtype=float), num_folds)
        out[f"{column}_ci"] = ci
        out[f"{column}_lo"] = out[column] - ci
        out[f"{column}_hi"] = out[column] + ci
    return out


def _value_at_budget(frame: pd.DataFrame, metric: str, budget: int) -> tuple[float, float]:
    eligible = frame[frame["f_theta_calls"] <= budget].sort_values("f_theta_calls")
    if eligible.empty:
        return math.nan, math.nan
    row = eligible.iloc[-1]
    return float(row[metric]), float(row.get(f"{metric}_ci", 0.0))


def _first_calls_to_reach(
    frame: pd.DataFrame,
    metric: str,
    threshold: float,
) -> float:
    if not np.isfinite(threshold) or threshold <= 0.0:
        return math.nan
    eligible = frame[frame[metric] >= threshold].sort_values("f_theta_calls")
    if eligible.empty:
        return math.nan
    return float(eligible.iloc[0]["f_theta_calls"])


def _format_rate(mean: float, ci: float) -> str:
    if not np.isfinite(mean):
        return "n/a"
    if ci and np.isfinite(ci):
        return f"{100.0 * mean:.1f} +/- {100.0 * ci:.1f}"
    return f"{100.0 * mean:.1f}"


def _aggregate_outputs(
    args: argparse.Namespace,
    *,
    manifest: pd.DataFrame,
    baseline_dir: Path,
) -> None:
    trm = _load_trm_profile(baseline_dir, num_folds=args.num_folds)
    trm = _add_ci_columns(trm, ["exact_solved"], num_folds=args.num_folds)
    trm["f_theta_calls"] = trm["step"].astype(int)
    trm["mode"] = "deterministic"
    trm["particles"] = 1
    trm["method"] = "Deterministic TRM"
    trm["split"] = args.split
    trm.to_csv(args.out / "trm_depth_profile.csv", index=False)
    if args.num_folds > 1:
        trm.to_csv(args.out / "trm_depth_profile_summary.csv", index=False)

    frontier_rows = [
        trm[
            [
                "split",
                "mode",
                "method",
                "particles",
                "step",
                "f_theta_calls",
                "exact_solved",
                "exact_solved_std",
                "exact_solved_ci",
                "exact_solved_lo",
                "exact_solved_hi",
            ]
        ].rename(columns={"exact_solved": "exact_accuracy"})
    ]

    final_trm = float(trm["exact_solved"].iloc[-1])
    deterministic_budget = int(trm["f_theta_calls"].iloc[-1])
    summary_rows: list[dict] = []

    summary_rows.append(
        {
            "split": args.split,
            "mode": "deterministic",
            "method": "Deterministic TRM",
            "particles": 1,
            "terminal_step": int(trm["step"].iloc[-1]),
            "terminal_f_theta_calls": deterministic_budget,
            "accuracy_at_deterministic_budget": final_trm,
            "accuracy_at_deterministic_budget_ci": float(
                trm["exact_solved_ci"].iloc[-1]
            ),
            "terminal_exact_accuracy": final_trm,
            "terminal_exact_accuracy_ci": float(trm["exact_solved_ci"].iloc[-1]),
            "terminal_oracle_accuracy": final_trm,
            "terminal_oracle_accuracy_ci": float(trm["exact_solved_ci"].iloc[-1]),
            "calls_to_match_trm": float(deterministic_budget)
            if args.split != "impossible" and final_trm > 0.0
            else math.nan,
            "mean_ess_terminal": math.nan,
            "elapsed_seconds": 0.0,
        }
    )

    for row in manifest.itertuples(index=False):
        run_dir = Path(row.run_dir)
        step = _load_step_profile(run_dir, num_folds=args.num_folds)
        step = _add_ci_columns(
            step,
            ["exact_accuracy", "any_exact_rate", "mean_ess"],
            num_folds=args.num_folds,
        )
        step["f_theta_calls"] = step["step"].astype(int) * int(row.particles)
        step["split"] = args.split
        step["mode"] = row.mode
        step["method"] = (
            f"Guided PF, S={row.particles}"
            if row.mode == "guided"
            else f"Unguided PF, S={row.particles}"
        )
        step["particles"] = int(row.particles)
        frontier_rows.append(step)

        acc_budget, acc_budget_ci = _value_at_budget(
            step, "exact_accuracy", deterministic_budget
        )
        final = step.iloc[-1]
        calls_to_match = (
            _first_calls_to_reach(step, "exact_accuracy", final_trm)
            if args.split != "impossible"
            else math.nan
        )
        summary_rows.append(
            {
                "split": args.split,
                "mode": row.mode,
                "method": step["method"].iloc[0],
                "particles": int(row.particles),
                "terminal_step": int(final["step"]),
                "terminal_f_theta_calls": int(final["f_theta_calls"]),
                "accuracy_at_deterministic_budget": acc_budget,
                "accuracy_at_deterministic_budget_ci": acc_budget_ci,
                "terminal_exact_accuracy": float(final["exact_accuracy"]),
                "terminal_exact_accuracy_ci": float(final["exact_accuracy_ci"]),
                "terminal_oracle_accuracy": float(final["any_exact_rate"]),
                "terminal_oracle_accuracy_ci": float(final["any_exact_rate_ci"]),
                "calls_to_match_trm": calls_to_match,
                "mean_ess_terminal": float(final["mean_ess"]),
                "elapsed_seconds": float(row.elapsed_seconds),
            }
        )

    frontier = pd.concat(frontier_rows, ignore_index=True, sort=False)
    frontier.to_csv(args.out / "compute_frontier.csv", index=False)

    summary = pd.DataFrame(summary_rows).sort_values(["mode", "particles"])
    summary.to_csv(args.out / "compute_summary.csv", index=False)

    guided = summary[summary["mode"].isin(["deterministic", "guided"])].copy()
    guided["S"] = guided["particles"].map(lambda value: f"{int(value)}")
    guided["At TRM budget"] = [
        _format_rate(mean, ci)
        for mean, ci in zip(
            guided["accuracy_at_deterministic_budget"],
            guided["accuracy_at_deterministic_budget_ci"],
        )
    ]
    guided["Terminal MAP"] = [
        _format_rate(mean, ci)
        for mean, ci in zip(
            guided["terminal_exact_accuracy"],
            guided["terminal_exact_accuracy_ci"],
        )
    ]
    guided["Terminal oracle"] = [
        _format_rate(mean, ci)
        for mean, ci in zip(
            guided["terminal_oracle_accuracy"],
            guided["terminal_oracle_accuracy_ci"],
        )
    ]
    guided["Calls to TRM"] = guided["calls_to_match_trm"].map(
        lambda value: "n/a" if not np.isfinite(value) else f"{int(value)}"
    )
    quality = guided[
        [
            "method",
            "S",
            "At TRM budget",
            "Terminal MAP",
            "Terminal oracle",
            "Calls to TRM",
        ]
    ].rename(columns={"method": "Method"})
    quality.to_csv(args.out / "quality_table.csv", index=False)
    (args.out / "quality_table.md").write_text(markdown_table(quality, digits=3) + "\n")


def main() -> None:
    args = parse_args()
    if args.num_folds < 1:
        raise ValueError(f"--num-folds must be >= 1, got {args.num_folds}")
    args.fold_seed = args.seed if args.fold_seed is None else args.fold_seed
    args.particles = sorted({int(value) for value in args.particles})
    if any(value < 1 for value in args.particles):
        raise ValueError("--particles values must all be >= 1")

    profile_cfg = PROFILE_DEFAULTS[args.profile]
    if args.checkpoint is None:
        args.checkpoint = profile_cfg["checkpoint"]
    if args.data_dir is None:
        args.data_dir = profile_cfg["data_dir"]
    if args.out is None:
        args.out = _default_out(args)

    if args.smoke:
        args.particles = [1, 4]
        args.total_steps = 12
        args.batch_size = 4
        args.n_batches = 2
        print("Smoke mode: S={1,4}, steps=12, batches=2, batch-size=4")

    args.out.mkdir(parents=True, exist_ok=True)
    _write_json(
        args.out / "config.json",
        {
            key: str(value) if isinstance(value, Path) else value
            for key, value in vars(args).items()
        },
    )

    device = torch.device(args.device) if args.device else select_device()
    print(f"Device: {device}")
    print(f"Loading checkpoint: {args.checkpoint}")
    trm = load_trm_backbone_checkpoint(args.checkpoint, map_location=device, use_ema=True)
    trm.eval().to(device)

    print(f"Loading {args.n_batches} batches (split={args.split})")
    raw_batches = load_batches(
        data_dir=args.data_dir,
        split=args.split,
        batch_size=args.batch_size,
        n_batches=args.n_batches,
        device=device,
    )

    fold_batches = None
    fold_infos = None
    if args.num_folds > 1:
        fold_batches, fold_infos = build_example_folds(
            raw_batches,
            num_folds=args.num_folds,
            seed=args.fold_seed,
            batch_size=args.batch_size,
        )
        _write_json(
            args.out / "fold_manifest.json",
            {
                "num_folds": args.num_folds,
                "fold_seed": args.fold_seed,
                "folds": [
                    {
                        "fold_index": info.fold_index,
                        "fold_name": f"fold_{info.fold_index + 1:02d}",
                        "num_examples": info.num_examples,
                        "num_batches": info.num_batches,
                    }
                    for info in fold_infos
                ],
            },
        )
        print(
            f"Running {args.num_folds}-fold mode over "
            f"{sum(info.num_examples for info in fold_infos)} examples"
        )

    manifest_rows: list[dict] = []
    baseline_source: Path | None = None
    for particles in args.particles:
        for mode, beta_override in MODE_SPECS:
            beta = args.beta if beta_override is None else beta_override
            out_dir = args.out / mode / _particle_tag(particles)
            print(
                f"\nRunning {mode} condition: S={particles}, beta={beta}, "
                f"sigma={args.sigma}, steps={args.total_steps}"
            )
            start = time.perf_counter()
            _run_condition(
                args=args,
                mode=mode,
                particles=particles,
                beta=beta,
                trm=trm,
                device=device,
                raw_batches=raw_batches,
                fold_batches=fold_batches,
                fold_infos=fold_infos,
                out_dir=out_dir,
                baseline_source=baseline_source,
            )
            elapsed = time.perf_counter() - start
            if baseline_source is None:
                baseline_source = out_dir
            manifest_rows.append(
                {
                    "mode": mode,
                    "particles": particles,
                    "beta": beta,
                    "sigma": args.sigma,
                    "ess_threshold": args.ess_threshold,
                    "run_dir": str(out_dir),
                    "elapsed_seconds": elapsed,
                }
            )

    if baseline_source is None:
        raise RuntimeError("No conditions were run; cannot aggregate benchmark outputs")

    manifest = pd.DataFrame(manifest_rows)
    manifest.to_csv(args.out / "run_manifest.csv", index=False)
    _aggregate_outputs(args, manifest=manifest, baseline_dir=baseline_source)
    print(f"\nSaved test-time compute benchmark to: {args.out}")


if __name__ == "__main__":
    main()
