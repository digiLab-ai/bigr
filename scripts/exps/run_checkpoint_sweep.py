"""run_checkpoint_sweep - guided vs deterministic BIGR across intermediate TRM checkpoints (paper Figure 8).

For each ``epoch_*.ckpt`` in --checkpoint-dir (``last.ckpt`` excluded unless --include-last),
runs the four particle-filter conditions
  1) test + guided    (beta=0.25)
  2) test + unguided  (beta=0.0)
  3) impossible + guided
  4) impossible + unguided
with S=16, N=48, sigma=0.3, tau_ESS=0.3 over the same k folds (default 5) of a 64 x 32 subset
of each split, saving per-fold artefacts and per-condition fold summaries exactly like
``scripts/exps/run_pf.py``. Checkpoint-level tables (checkpoint_condition_summary.csv,
condition_overall_summary.csv, checkpoint_manifest.json) are written under --out.

The cached run is assets/runs/sudoku/pf_checkpoint_sweep, regenerated by
``bash scripts/run_experiments.sh --profile sudoku_extreme --checkpoint-sweep`` once the
intermediate checkpoints are in place (``python scripts/download_checkpoints.py
--all-checkpoints``); fig_checkpoint.py also needs the training run's Lightning log copied
there as training_progress.csv. Sudoku-Extreme only.

Examples
--------
python scripts/exps/run_checkpoint_sweep.py --checkpoint-dir data/sudoku_extreme/checkpoints \\
    --num-folds 5 --fold-seed 31 --out assets/runs/sudoku/pf_checkpoint_sweep
python scripts/exps/run_checkpoint_sweep.py --smoke --out tmp/runs_smoke/sudoku/pf_checkpoint_sweep
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
import traceback
from pathlib import Path

import pandas as pd
import torch

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR
while not (REPO_ROOT / "src").exists() and REPO_ROOT != REPO_ROOT.parent:
    REPO_ROOT = REPO_ROOT.parent
if str(REPO_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "src"))
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import run_pf as pf
from fold_utils import build_example_folds, summarize_numeric_df
from bigr import (
    TRMCoreDecoder,
    TRMCoreEmbedder,
    TRMCoreQHead,
    TRMNativeCycleFTheta,
    load_trm_backbone_checkpoint,
    select_device,
)

DEFAULT_CHECKPOINT_DIR = pf.PROFILE_DEFAULTS["sudoku_extreme"]["checkpoint"].parent
DEFAULT_DATA_DIR = pf.PROFILE_DEFAULTS["sudoku_extreme"]["data_dir"]
DEFAULT_OUT = REPO_ROOT / "assets" / "runs" / "sudoku" / "pf_checkpoint_sweep"
EPOCH_RE = re.compile(r"epoch_(\d+)\.ckpt$")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Run PF test/impossible guided/unguided across intermediate checkpoints",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument(
        "--checkpoint-dir", type=Path, default=DEFAULT_CHECKPOINT_DIR,
        help="Directory of intermediate epoch_*.ckpt files from one Sudoku-Extreme training run.",
    )
    p.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    p.add_argument(
        "--device",
        default=None,
        help="Target device (cuda/mps/cpu). Auto-selects CUDA > MPS > CPU if omitted.",
    )
    p.add_argument("--particles", type=int, default=16)
    p.add_argument("--total-steps", type=int, default=48)
    p.add_argument("--sigma", type=float, default=0.3)
    p.add_argument("--ess-threshold", type=float, default=0.3)
    p.add_argument("--seed", type=int, default=31)
    p.add_argument("--batch-size", type=int, default=64)
    p.add_argument("--n-batches", type=int, default=32, help="64 x 32 puzzles per split is the Figure 8 protocol.")
    p.add_argument("--num-folds", type=int, default=5)
    p.add_argument("--fold-seed", type=int, default=31)
    p.add_argument(
        "--include-last",
        action="store_true",
        help="Include last.ckpt (excluded by default).",
    )
    p.add_argument(
        "--checkpoint-all-steps",
        action="store_true",
        help="Record checkpoint arrays at every outer step.",
    )
    p.add_argument(
        "--disable-step-cpu-metrics",
        action="store_true",
        help="Skip per-step diagnostic materialization/aggregation.",
    )
    p.add_argument(
        "--smoke",
        action="store_true",
        help="Quick smoke check: 2 batches, 4 particles, 12 steps.",
    )
    p.set_defaults(smoke=False, checkpoint_all_steps=False, include_last=False)
    return p.parse_args()


def _write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2))


def _checkpoint_epoch(path: Path) -> int:
    m = EPOCH_RE.match(path.name)
    return int(m.group(1)) if m else 10**12


def _list_checkpoints(checkpoint_dir: Path, include_last: bool) -> list[Path]:
    checkpoints = []
    for ckpt in checkpoint_dir.glob("*.ckpt"):
        if ckpt.name == "last.ckpt" and not include_last:
            continue
        checkpoints.append(ckpt)
    checkpoints.sort(key=lambda p: (_checkpoint_epoch(p), p.name))
    return checkpoints


def _condition_grid() -> list[dict]:
    return [
        {"name": "test_guided", "split": "test", "beta": 0.25, "guided": True},
        {"name": "test_unguided", "split": "test", "beta": 0.0, "guided": False},
        {"name": "impossible_guided", "split": "impossible", "beta": 0.25, "guided": True},
        {"name": "impossible_unguided", "split": "impossible", "beta": 0.0, "guided": False},
    ]


def _extract_final_row(step_summary_path: Path) -> dict:
    frame = pd.read_csv(step_summary_path).sort_values("step")
    tail = frame.iloc[-1]
    out = {"step": int(tail["step"])}
    for col in (
        "exact_accuracy_mean",
        "exact_accuracy_std",
        "any_exact_rate_mean",
        "any_exact_rate_std",
        "mean_ess_mean",
        "mean_ess_std",
        "weight_entropy_mean",
        "weight_entropy_std",
    ):
        if col in tail.index:
            out[col] = float(tail[col])
    return out


def main() -> None:
    args = parse_args()
    if args.num_folds < 1:
        raise ValueError(f"--num-folds must be >= 1, got {args.num_folds}")
    if args.fold_seed is None:
        args.fold_seed = args.seed

    if args.smoke:
        args.particles = 4
        args.total_steps = 12
        args.batch_size = 4
        args.n_batches = 2
        print("Smoke mode: particles=4, steps=12, batches=2")

    if not args.checkpoint_dir.exists():
        raise FileNotFoundError(f"Checkpoint directory not found: {args.checkpoint_dir}")
    if not args.data_dir.exists():
        raise FileNotFoundError(f"Data directory not found: {args.data_dir}")

    checkpoints = _list_checkpoints(args.checkpoint_dir, include_last=args.include_last)
    if not checkpoints:
        raise RuntimeError(
            f"No checkpoints found in {args.checkpoint_dir} "
            f"(include_last={args.include_last})."
        )

    args.out.mkdir(parents=True, exist_ok=True)
    _write_json(
        args.out / "config.json",
        {k: str(v) if isinstance(v, Path) else v for k, v in vars(args).items()},
    )

    device = torch.device(args.device) if args.device else select_device()
    print(f"Device: {device}")
    print(f"Checkpoints: {len(checkpoints)} found in {args.checkpoint_dir}")
    print("Preparing fixed fold splits per evaluation split...")

    split_to_raw = {}
    split_to_fold_batches = {}
    split_to_fold_infos = {}
    for split in ("test", "impossible"):
        raw_batches = pf.load_batches(
            data_dir=args.data_dir,
            split=split,
            batch_size=args.batch_size,
            n_batches=args.n_batches,
            device=device,
        )
        fold_batches, fold_infos = build_example_folds(
            raw_batches,
            num_folds=args.num_folds,
            seed=args.fold_seed,
            batch_size=args.batch_size,
        )
        split_to_raw[split] = raw_batches
        split_to_fold_batches[split] = fold_batches
        split_to_fold_infos[split] = fold_infos

    summary_rows: list[dict] = []
    skipped_checkpoints: list[dict] = []
    last_error: Exception | None = None
    condition_grid = _condition_grid()
    total_runs = len(checkpoints) * len(condition_grid) * args.num_folds
    print(
        f"Running sweep: {len(checkpoints)} checkpoints x {len(condition_grid)} conditions "
        f"x {args.num_folds} folds = {total_runs} runs"
    )

    for ckpt_idx, ckpt_path in enumerate(checkpoints, start=1):
        ckpt_name = ckpt_path.stem
        ckpt_epoch = _checkpoint_epoch(ckpt_path)
        ckpt_out_root = args.out / ckpt_name
        print(f"\n=== [{ckpt_idx}/{len(checkpoints)}] checkpoint={ckpt_path.name} ===")
        checkpoint_row_start = len(summary_rows)
        try:
            print("Loading model...")
            trm = load_trm_backbone_checkpoint(
                ckpt_path, map_location=device, use_ema=True
            )
            trm.eval().to(device)
            embedder = TRMCoreEmbedder(trm)
            decoder = TRMCoreDecoder(trm)
            q_head = TRMCoreQHead(trm)
            f_theta = TRMNativeCycleFTheta(trm)
            ckpt_out_root.mkdir(parents=True, exist_ok=True)

            for cond in condition_grid:
                cond_name = cond["name"]
                split = cond["split"]
                beta = float(cond["beta"])
                cond_out = ckpt_out_root / cond_name
                print(
                    f"\n  -> {cond_name}: split={split} beta={beta} "
                    f"folds={args.num_folds}"
                )

                run_args = argparse.Namespace(
                    checkpoint=ckpt_path,
                    data_dir=args.data_dir,
                    split=split,
                    out=cond_out,
                    device=args.device,
                    particles=args.particles,
                    total_steps=args.total_steps,
                    sigma=args.sigma,
                    beta=beta,
                    ess_threshold=args.ess_threshold,
                    seed=args.seed,
                    batch_size=args.batch_size,
                    n_batches=args.n_batches,
                    smoke=False,
                    save_particle_scores=None,
                    checkpoint_all_steps=args.checkpoint_all_steps,
                    num_folds=args.num_folds,
                    fold_seed=args.fold_seed,
                    disable_step_cpu_metrics=args.disable_step_cpu_metrics,
                )

                fold_outputs: list[dict] = []
                fold_batches = split_to_fold_batches[split]
                fold_infos = split_to_fold_infos[split]
                for fold_idx, (fold_raw_batches, fold_info) in enumerate(
                    zip(fold_batches, fold_infos),
                    start=1,
                ):
                    fold_name = f"fold_{fold_idx:02d}"
                    print(
                        f"     [{cond_name}/{fold_name}] "
                        f"examples={fold_info.num_examples} batches={fold_info.num_batches}"
                    )
                    fold_outputs.append(
                        pf._run_pf_single(
                            args=run_args,
                            trm=trm,
                            device=device,
                            embedder=embedder,
                            decoder=decoder,
                            q_head=q_head,
                            f_theta=f_theta,
                            raw_batches=fold_raw_batches,
                            out_dir=cond_out / fold_name,
                            save_particle_scores_dir=None,
                            save_particle_trace_dir=None,
                            fold_meta={
                                "checkpoint_sweep_mode": True,
                                "checkpoint_name": ckpt_path.name,
                                "checkpoint_epoch": ckpt_epoch,
                                "condition": cond_name,
                                "guided": bool(cond["guided"]),
                                "fold_mode": True,
                                "fold_index": fold_idx,
                                "fold_name": fold_name,
                                "num_folds": args.num_folds,
                                "fold_seed": args.fold_seed,
                                "fold_num_examples": fold_info.num_examples,
                                "fold_num_batches": fold_info.num_batches,
                            },
                        )
                    )

                pf._summarize_fold_outputs(fold_outputs, cond_out, fold_infos, run_args)
                final = _extract_final_row(cond_out / "step_metrics_summary.csv")
                summary_rows.append(
                    {
                        "checkpoint": ckpt_path.name,
                        "checkpoint_stem": ckpt_name,
                        "checkpoint_epoch": ckpt_epoch,
                        "condition": cond_name,
                        "split": split,
                        "guided": bool(cond["guided"]),
                        "beta": beta,
                        **final,
                        "path": str(cond_out.relative_to(args.out)),
                    }
                )

            del trm
            if torch.cuda.is_available() and device.type == "cuda":
                torch.cuda.empty_cache()
        except Exception as exc:
            print(
                f"[WARN] Skipping checkpoint {ckpt_path.name} due to error: "
                f"{type(exc).__name__}: {exc}"
            )
            traceback.print_exc()
            last_error = exc
            # Roll back any partial summary rows for this checkpoint.
            del summary_rows[checkpoint_row_start:]
            # Remove any partial artefacts for this checkpoint.
            if ckpt_out_root.exists():
                shutil.rmtree(ckpt_out_root, ignore_errors=True)
            skipped_checkpoints.append(
                {
                    "checkpoint": ckpt_path.name,
                    "checkpoint_stem": ckpt_name,
                    "checkpoint_epoch": ckpt_epoch,
                    "error_type": type(exc).__name__,
                    "error_message": str(exc),
                }
            )
            if torch.cuda.is_available() and device.type == "cuda":
                torch.cuda.empty_cache()
            continue

    if not summary_rows:
        error_types = sorted({entry["error_type"] for entry in skipped_checkpoints})
        if len(error_types) == 1 and last_error is not None:
            # Every checkpoint failed the same way: a programming error, not a bad checkpoint.
            print(f"All {len(checkpoints)} checkpoints failed with {error_types[0]}; re-raising.")
            raise last_error
        raise RuntimeError("All checkpoints failed; no valid results produced.")
    summary_df = pd.DataFrame(summary_rows).sort_values(
        ["checkpoint_epoch", "condition"]
    )
    summary_df.to_csv(args.out / "checkpoint_condition_summary.csv", index=False)

    overall_df = summarize_numeric_df(
        summary_df,
        group_cols=["condition", "split", "guided", "beta"],
    )
    overall_df.to_csv(args.out / "condition_overall_summary.csv", index=False)

    _write_json(
        args.out / "checkpoint_manifest.json",
        {
            "checkpoint_dir": str(args.checkpoint_dir),
            "data_dir": str(args.data_dir),
            "num_checkpoints": len(checkpoints),
            "num_checkpoints_skipped": len(skipped_checkpoints),
            "checkpoints": [p.name for p in checkpoints],
            "skipped_checkpoints": skipped_checkpoints,
            "num_conditions": len(condition_grid),
            "conditions": condition_grid,
            "num_folds": args.num_folds,
            "fold_seed": args.fold_seed,
            "num_total_runs": total_runs,
            "outputs": {
                "checkpoint_condition_summary": "checkpoint_condition_summary.csv",
                "condition_overall_summary": "condition_overall_summary.csv",
            },
        },
    )
    print(f"\nSweep complete. Outputs saved to: {args.out}")


if __name__ == "__main__":
    main()
